const bySlug = new Map(JOBS.map((job) => [job.slug, job]));

export function getJob(slug: string) {
  return bySlug.get(slug);
}

export function jobsByCompany(companySlug: string) {
  return JOBS.filter((job) => job.companySlug === companySlug);
}

export function jobsByCategory(category: Job["category"]) {
  return JOBS.filter((job) => job.category === category);
}

export function relatedJobs(job: Job, limit = 3) {
  return JOBS.filter(
    (candidate) =>
      candidate.id !== job.id &&
      (candidate.companySlug === job.companySlug ||
        candidate.category === job.category),
  ).slice(0, limit);
}
